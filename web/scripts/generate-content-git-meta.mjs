/**
 * Precomputes the git-derived metadata that content-meta.ts used to gather by
 * shelling out to `git log` while rendering.
 *
 * Astro prerenders inside workerd now that the Cloudflare adapter is in play,
 * and workerd has no `node:child_process` — the import fails the build outright,
 * and `nodejs_compat` can't help because the sandbox cannot spawn processes at
 * all. Git still has to be read from Node, so it is read here, ahead of
 * `astro build`, and baked into a module the prerender environment can import.
 *
 * Runs from the `web/` directory; paths below are relative to it.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const CONTENT_ROOT = path.join("src", "content");
const OUTPUT_DIRECTORY = path.join("src", "generated");
const OUTPUT_PATH = path.join(OUTPUT_DIRECTORY, "content-git-meta.ts");

/** Collection name as used in the source -> its directory under src/content. */
const COLLECTION_DIRECTORIES = {
  blog: "blog",
  professionalExperience: "professional-experience",
  projects: "projects",
};

/**
 * @param {string[]} args
 * @returns {string[]} Trimmed, non-empty stdout lines, or [] if git failed.
 */
function git(args) {
  try {
    return execFileSync("git", args, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    })
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean);
  } catch {
    return [];
  }
}

/**
 * A shallow clone reports one commit for every file, which would silently
 * rewrite every publication date to the deploy date. Loud failure beats that.
 */
function assertFullHistory() {
  if (git(["rev-parse", "--is-shallow-repository"])[0] === "true") {
    throw new Error(
      "Repository is a shallow clone, so per-file commit dates are not " +
        "recoverable. Check out with full history (actions/checkout with " +
        "fetch-depth: 0) or run `git fetch --unshallow` before building.",
    );
  }
}

/** @returns {string[]} Every file under `directory`, as paths relative to cwd. */
function listFilesRecursively(directory) {
  /** @type {string[]} */
  const files = [];
  let entries;

  try {
    entries = readdirSync(directory, { withFileTypes: true });
  } catch {
    return files;
  }

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...listFilesRecursively(entryPath));
    } else if (entry.isFile()) {
      files.push(entryPath);
    }
  }

  return files;
}

function parseTimestamp(line) {
  const value = Number.parseInt(line ?? "", 10);
  return Number.isFinite(value) ? value : undefined;
}

function collectMetaForFile(filePath) {
  const lastCommit = git(["log", "-1", "--format=%H %ct", "--", filePath])[0];
  const [lastCommitHash, lastCommitTimestamp] = lastCommit?.split(" ") ?? [];

  const firstCommitLines = git([
    "log",
    "--diff-filter=A",
    "--follow",
    "--format=%ct",
    "--",
    filePath,
  ]);

  const repoPath = git(["ls-files", "--full-name", "--", filePath])[0] ?? filePath;

  return {
    diffHash: createHash("sha256").update(repoPath).digest("hex"),
    firstCommitSeconds: parseTimestamp(firstCommitLines[firstCommitLines.length - 1]),
    lastCommitHash: lastCommitHash || undefined,
    lastCommitSeconds: parseTimestamp(lastCommitTimestamp),
    repoPath,
  };
}

assertFullHistory();

/** @type {Record<string, Record<string, ReturnType<typeof collectMetaForFile>>>} */
const metaByCollection = {};
let entryCount = 0;

for (const [collection, directoryName] of Object.entries(COLLECTION_DIRECTORIES)) {
  const collectionRoot = path.join(CONTENT_ROOT, directoryName);
  /** @type {Record<string, ReturnType<typeof collectMetaForFile>>} */
  const entries = {};

  for (const filePath of listFilesRecursively(collectionRoot)) {
    // Astro's glob loader ids are the collection-relative path minus extension.
    const relativePath = path.relative(collectionRoot, filePath);
    const id = relativePath.slice(0, -path.extname(relativePath).length || undefined);
    entries[id] = collectMetaForFile(filePath);
    entryCount += 1;
  }

  metaByCollection[collection] = entries;
}

const contents = `// Generated by scripts/generate-content-git-meta.mjs. Do not edit by hand.

export type ContentGitMeta = {
  diffHash: string;
  firstCommitSeconds?: number;
  lastCommitHash?: string;
  lastCommitSeconds?: number;
  repoPath: string;
};

export const contentGitMeta: Record<string, Record<string, ContentGitMeta>> = ${JSON.stringify(
  metaByCollection,
  null,
  2,
)};
`;

mkdirSync(OUTPUT_DIRECTORY, { recursive: true });
writeFileSync(OUTPUT_PATH, contents);

console.log(`Wrote git metadata for ${entryCount} content files to ${OUTPUT_PATH}`);
